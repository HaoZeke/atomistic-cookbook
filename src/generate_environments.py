"""Generate downloadable CPU and default conda environment files.

Recipe authors write a single ``environment.yml`` without a CPU or GPU pin.
The website build turns that file into:

- ``environment-default.yml``: a byte-for-byte copy of the author file
- ``environment-cpu.yml``: the same spec plus the PyTorch CPU wheel index
  and the conda CPU extras already used by the CI installer

``eon-pet-neb`` is a consumer of this path, not a special case.
"""

from __future__ import annotations

import argparse
import copy
import re
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, MutableMapping, Union

import yaml


PathLike = Union[str, Path]

PYTORCH_CPU_INDEX = "https://download.pytorch.org/whl/cpu"
CPU_INDEX_FLAG = f"--extra-index-url {PYTORCH_CPU_INDEX}"
DEFAULT_NAME = "environment-default.yml"
CPU_NAME = "environment-cpu.yml"

# Shared with noxfile.update_dependencies: if the dry-run (or the author
# file) names the key, append the extra so the solve stays on CPU/nompi.
CONDA_CPU_EXTRAS = {
    "libtorch": "pytorch-cpu",
    "lammps-metatomic": "lammps-metatomic * cpu*nompi*",
    "plumed-metatomic": "plumed-metatomic * *nompi*",
}

_CPU_HEADER = (
    "# Generated by src/generate_environments.py from environment.yml.\n"
    "# Prefer this file on machines without a GPU.\n"
)


class _IndentedDumper(yaml.SafeDumper):
    """Keep sequence items indented under their parent key."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


DOWNLOAD_RST = """
.. container:: sphx-glr-download

    :download:`CPU environment: environment-cpu.yml <environment-cpu.yml>`

.. container:: sphx-glr-download

    :download:`Default environment: environment-default.yml\
 <environment-default.yml>`
"""


def conda_package_name(spec: str) -> str:
    """Return the package name from a conda dependency string."""
    text = spec.strip()
    if "::" in text:
        text = text.split("::", 1)[1]
    return re.split(r"[=<>!~\s]", text, maxsplit=1)[0]


def _string_deps(deps: Iterable[Any]) -> List[str]:
    return [dep.strip() for dep in deps if isinstance(dep, str)]


def _has_cpu_index(pip_items: Iterable[Any]) -> bool:
    for item in pip_items:
        if not isinstance(item, str):
            continue
        text = item.strip()
        if PYTORCH_CPU_INDEX in text:
            return True
    return False


def _pip_entry(deps: List[Any]) -> MutableMapping[str, Any] | None:
    for dep in deps:
        if isinstance(dep, dict) and "pip" in dep:
            return dep
    return None


def render_cpu_environment(environment: Mapping[str, Any]) -> Dict[str, Any]:
    """Return a CPU-oriented copy of a loaded environment mapping."""
    env: Dict[str, Any] = copy.deepcopy(dict(environment))
    deps = list(env.get("dependencies") or [])

    pip_entry = _pip_entry(deps)
    if pip_entry is not None:
        pip_items = list(pip_entry.get("pip") or [])
        if not _has_cpu_index(pip_items):
            pip_items.insert(0, CPU_INDEX_FLAG)
        pip_entry["pip"] = pip_items
        variables = dict(env.get("variables") or {})
        variables.setdefault("PIP_EXTRA_INDEX_URL", PYTORCH_CPU_INDEX)
        env["variables"] = variables

    existing = set(_string_deps(deps))
    names = {conda_package_name(dep) for dep in _string_deps(deps)}
    extras = [
        extra
        for key, extra in CONDA_CPU_EXTRAS.items()
        if key in names and extra not in existing
    ]
    if extras:
        insert_at = next(
            (
                index
                for index, dep in enumerate(deps)
                if isinstance(dep, dict) and "pip" in dep
            ),
            len(deps),
        )
        for offset, extra in enumerate(extras):
            deps.insert(insert_at + offset, extra)

    if extras or pip_entry is not None:
        env["dependencies"] = deps
    return env


def write_environment_variants(source: PathLike, dest_dir: PathLike) -> Dict[str, Path]:
    """Write ``environment-default.yml`` and ``environment-cpu.yml``.

    The default file is a byte copy of ``source`` so author comments stay
    intact. The CPU file is a rendered YAML document.
    """
    source = Path(source)
    dest_dir = Path(dest_dir)
    if not source.is_file():
        raise FileNotFoundError(source)
    dest_dir.mkdir(parents=True, exist_ok=True)

    default_path = dest_dir / DEFAULT_NAME
    cpu_path = dest_dir / CPU_NAME
    default_path.write_bytes(source.read_bytes())

    loaded = yaml.safe_load(source.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        loaded = {}
    cpu_env = render_cpu_environment(loaded)
    with cpu_path.open("w", encoding="utf-8") as handle:
        handle.write(_CPU_HEADER)
        yaml.dump(
            cpu_env,
            handle,
            Dumper=_IndentedDumper,
            sort_keys=False,
            default_flow_style=False,
        )
    return {"default": default_path, "cpu": cpu_path}


def append_environment_downloads(rst_path: PathLike) -> None:
    """Append sphinx ``:download:`` links for the generated env files."""
    rst_path = Path(rst_path)
    text = rst_path.read_text(encoding="utf-8")
    if "environment-cpu.yml <environment-cpu.yml>" in text:
        return
    rst_path.write_text(text.rstrip() + "\n" + DOWNLOAD_RST, encoding="utf-8")


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Write environment-default.yml and environment-cpu.yml "
            "from a recipe environment.yml."
        )
    )
    parser.add_argument("source", type=Path, help="Author environment.yml")
    parser.add_argument(
        "-o",
        "--output-dir",
        type=Path,
        required=True,
        help="Directory that receives the two generated files",
    )
    args = parser.parse_args(argv)
    paths = write_environment_variants(args.source, args.output_dir)
    for kind, path in paths.items():
        print(f"{kind}: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
